#!/bin/bash
# Writes src/fontIds.h to stdout: one id per font set, the SHA256 sum of its header files (same scheme as before).
set -e
cd "$(dirname "$0")/../builtinFonts"
python3 - <<'PY'
import hashlib
def fid(names):
    s = sum(int(hashlib.sha256(open(f"./{n}.h", "rb").read()).hexdigest(), 16) for n in names)
    return s % (2 ** 32) - 2 ** 31
ids = {f"MONO_{z}_FONT_ID": [f"mono_{z}_{st}" for st in ("regular", "bold", "bolditalic", "italic")] for z in (9, 10, 11, 12, 14, 16)}
ids["UI_10_FONT_ID"] = ["monoui_10_regular", "monoui_10_bold"]
ids["UI_12_FONT_ID"] = ["monoui_12_regular", "monoui_12_bold"]
ids["SMALL_FONT_ID"] = ["monoui_8_regular"]
print("// The contents of this file are generated by ./lib/EpdFont/scripts/build-font-ids.sh")
print("#pragma once\n")
for k, v in ids.items():
    print(f"#define {k} ({fid(v)})")
print('\n// Font ID 0 is reserved as the "not found" sentinel.\n// Guard against any hash accidentally producing 0.')
for k in ids:
    print(f'static_assert({k} != 0, "Font ID collision with sentinel");')
PY
